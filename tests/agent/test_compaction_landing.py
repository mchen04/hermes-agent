def _compressor(**attrs):
    with patch("agent.context_compressor.get_model_context_length", return_value=WINDOW):
        compressor = ContextCompressor(
            model="test/model", threshold_percent=0.8, threshold_tokens_cap=TRIGGER, protect_first_n=0,
            protect_last_n=20, quiet_mode=True, config_context_length=WINDOW,
        )
        _ = compressor.context_length
    for name, value in attrs.items():
        setattr(compressor, name, value)
    return compressor


def _exchange(i):
    call_id = f"call_{i}"
    return [
        {"role": "user", "content": f"question {i}: " + "please check the board and the logs " * 6},
        {"role": "assistant", "content": "", "tool_calls": [
            {"id": call_id, "type": "function", "function": {"name": "terminal", "arguments": json.dumps({"command": f"ls {i}"})}}]},
        {"role": "tool", "tool_call_id": call_id, "content": f"output {i}\n" + "line of tool output\n" * 300},
        {"role": "assistant", "content": f"answer {i}: " + "here is what I found in the logs " * 12},
    ]


def _transcript(exchanges=60):
    messages = []
    for i in range(exchanges):
        messages += _exchange(i)
    return messages


def _landed(compressed):
    return int(RATIO * (OVERHEAD + estimate_messages_tokens_rough(compressed)))


def _summary_llm(prompt, started):
    return BIG_SUMMARY


def _compress(compressor, messages):
    with patch.object(compressor, "_call_summary_llm", side_effect=_summary_llm):
        return compressor.compress(messages, current_tokens=TRIGGER)


def test_default_tail_lands_far_above_the_target():
    compressor = _compressor(request_overhead_tokens=OVERHEAD, real_token_ratio=RATIO)
    assert _landed(_compress(compressor, _transcript())) > TARGET


def test_a_landing_target_makes_one_compaction_land_under_it():
    compressor = _compressor(
        post_compaction_target_tokens=TARGET, summary_max_chars=CAP, request_overhead_tokens=OVERHEAD,
        real_token_ratio=RATIO,
    )
    messages = _transcript()
    compressed = _compress(compressor, messages)
    assert _landed(compressed) <= TARGET
    assert (compressed[-1]["role"], compressed[-1]["content"]) == (messages[-1]["role"], messages[-1]["content"])
    assert any(m.get("role") == "user" and m.get("content") == messages[-4]["content"] for m in compressed)


def test_the_target_defaults_to_a_share_of_the_trigger_and_never_exceeds_it():
    assert _compressor().landing_target_tokens == 0
    assert _compressor(post_compaction_target_ratio=0.5).landing_target_tokens == TRIGGER // 2
    assert _compressor(post_compaction_target_tokens=TARGET).landing_target_tokens == TARGET
    assert _compressor(post_compaction_target_tokens=10 * TRIGGER).landing_target_tokens == TRIGGER


def test_an_unreachable_target_keeps_the_default_tail():
    plain = _compressor(request_overhead_tokens=OVERHEAD, real_token_ratio=RATIO)
    hopeless = _compressor(
        post_compaction_target_tokens=OVERHEAD, request_overhead_tokens=OVERHEAD, real_token_ratio=RATIO,
    )
    messages = _transcript()
    assert len(_compress(hopeless, messages)) == len(_compress(plain, messages))


def test_the_real_token_ratio_comes_from_the_provider_usage_anchor():
    from agent.context_compressor_landing import prime_landing_estimate
    from agent.usage_anchor import capture_usage_anchor

    compressor = _compressor()
    messages = _transcript(10)
    priced = messages[:-1]
    system_prompt = "s" * 40_000
    agent = SimpleNamespace(
        context_compressor=compressor, _cached_system_prompt=system_prompt, ephemeral_system_prompt=None,
        tools=[], _usage_anchor=capture_usage_anchor(29_000, 300, priced),
    )
    prime_landing_estimate(agent, messages)
    rough = 10_000 + sum(cc._estimate_msg_budget_tokens(m) for m in priced)
    assert compressor.request_overhead_tokens == 10_000
    assert compressor.real_token_ratio == pytest.approx(29_000 / rough)
    assert compressor.real_overhead_tokens == int(compressor.real_token_ratio * 10_000)


def test_two_real_readings_separate_the_fixed_prompt_from_the_messages():
    compressor = _compressor(request_overhead_tokens=20_000)
    compressor.post_compaction_target_tokens = TARGET
    compressor.awaiting_real_usage_after_compression = True
    compressed = _transcript(3)
    compressor.note_landing_messages(compressed)
    small = compressor._landing_messages_rough
    compressor.update_from_response({"prompt_tokens": 26_000 + int(1.5 * small), "completion_tokens": 10})
    compressor.observe_real_prompt_tokens(26_000 + int(1.5 * 50_000), 50_000)
    assert compressor.real_token_ratio == pytest.approx(1.5, abs=0.01)
    assert compressor.real_overhead_tokens == pytest.approx(26_000, abs=50)


def test_a_stale_anchor_leaves_the_ratio_alone():
    from agent.context_compressor_landing import prime_landing_estimate
    from agent.usage_anchor import capture_usage_anchor

    compressor = _compressor(real_token_ratio=1.3)
    messages = _transcript(10)
    agent = SimpleNamespace(
        context_compressor=compressor, _cached_system_prompt="s", ephemeral_system_prompt=None, tools=[],
        _usage_anchor=capture_usage_anchor(29_000, 300, [{"role": "user", "content": "other"}]),
    )
    prime_landing_estimate(agent, messages)
    assert compressor.real_token_ratio == 1.3


def test_a_capped_summary_keeps_constraints_and_decisions_and_drops_the_logs():
    compressor = _compressor(summary_max_chars=CAP)
    turns = _exchange(1) + [{"role": "user", "content": "do not deploy to main"}]
    with patch.object(compressor, "_call_summary_llm", side_effect=_summary_llm):
        summary = compressor._generate_summary(turns)
    body = compressor._strip_summary_prefix(summary)
    assert len(body) <= CAP
    assert "## Constraints & Preferences" in body and "Never deploy to main" in body
    assert "## Key Decisions" in body and "tie-break by time" in body
    assert "## Completed Actions" not in body and "## Detailed Session Log" not in body
    assert "do not deploy to main" in body


def test_an_uncapped_summary_is_unchanged():
    compressor = _compressor()
    with patch.object(compressor, "_call_summary_llm", side_effect=_summary_llm):
        summary = compressor._generate_summary(_exchange(1))
    assert "## Completed Actions" in summary and "## Detailed Session Log" in summary


def test_verbatim_user_messages_hold_only_the_users_own_words():
    turns = [
        {"role": "user", "content": SKILL_SCAFFOLD},
        {"role": "assistant", "content": "ok"},
        {"role": "user", "content": KANBAN_WAKE},
        {"role": "assistant", "content": "ok"},
        {"role": "user", "content": INTERNAL},
        {"role": "assistant", "content": "ok"},
        {"role": "user", "content": TRIGGER_NOTE},
        {"role": "assistant", "content": "ok"},
        {"role": "user", "content": "notified", "display_kind": "internal_notification"},
        {"role": "user", "content": "close the Ko session"},
    ]
    section = cc._build_verbatim_user_section(turns)
    assert "update me on all cards" in section
    assert "what model are they using?" in section
    assert "close the Ko session" in section
    for leaked in ("[kanban]", "skill is auto-loaded", "Always read the board", "scripts/foo.js",
                   "INTERNAL NOTIFICATION", "Triggering message id", "notified"):
        assert leaked not in section


