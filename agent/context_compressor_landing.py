def compact_update_instruction(historical_heading: str, char_budget: int) -> str:
    return (
        "Rewrite the summary using this exact structure. Keep every constraint, preference and decision that "
        "still applies; carry live items forward with their current state; drop work that is finished and no "
        f"longer matters. Update \"{historical_heading}\" to the user's most recent unfulfilled input; write "
        f"\"None\" only if the last exchange was fully resolved. The result must stay under {char_budget} characters."
    )


def _split_sections(summary: str) -> tuple[str, list[str]]:
    starts = [m.start() for m in _SECTION_START_RE.finditer(summary)]
    if not starts:
        return summary, []
    head = summary[:starts[0]]
    bounds = starts + [len(summary)]
    return head, [summary[bounds[i]:bounds[i + 1]] for i in range(len(starts))]


def _rank(section: str, required: Sequence[str], priority: Sequence[str]) -> Optional[int]:
    if any(section.startswith(heading) for heading in required):
        return -1
    for index, heading in enumerate(priority):
        if section.startswith(heading):
            return index
    return None


def fit_summary_to_cap(
    summary: str, cap: int, required: Sequence[str], priority: Sequence[str], dropped: Sequence[str] = (),
) -> str:
    if cap <= 0:
        return summary
    head, sections = _split_sections(summary)
    sections = [section for section in sections if not section.startswith(tuple(dropped))]
    if len(head) + sum(map(len, sections)) <= cap:
        return (head + "".join(sections)).rstrip()
    ranks = [_rank(section, required, priority) for section in sections]
    unknown_rank = len(priority)
    order = sorted(
        range(len(sections)),
        key=lambda i: (ranks[i] if ranks[i] is not None else unknown_rank, i),
    )
    room = cap - len(head)
    kept: dict[int, str] = {}
    for i in order:
        section = sections[i]
        if ranks[i] == -1 or len(section) <= room:
            kept[i] = section
            room -= len(section)
            continue
        if room >= SECTION_MIN_CHARS:
            kept[i] = elide(section.rstrip(), room - 2) + "\n\n"
            room -= len(kept[i])
    fitted = head + "".join(kept[i] for i in range(len(sections)) if i in kept)
    return fitted.rstrip()


def summary_reserve_tokens(cap_chars: int, fallback_tokens: int, chars_per_token: int, prior_tokens: int = 0) -> int:
    if cap_chars > 0:
        return cap_chars // max(1, chars_per_token)
    if prior_tokens > 0:
        return min(fallback_tokens, int(prior_tokens * SUMMARY_GROWTH_MARGIN))
    return fallback_tokens


class LandingMixin:
    post_compaction_target_tokens: int = 0
    post_compaction_target_ratio: float = 0.0
    summary_max_chars: int = 0
    request_overhead_tokens: int = 0
    real_token_ratio: float = 1.0
    real_overhead_tokens: int = 0
    _post_compaction_point: Optional[tuple[int, int]] = None
    _landing_messages_rough: int = 0
    _last_landing_projection: int = 0

    @property
    def landing_target_tokens(self) -> int:
        return landing_target(self.threshold_tokens, self.post_compaction_target_tokens, self.post_compaction_target_ratio)

    def _messages_rough(self, messages: list[dict[str, Any]]) -> int:
        price = self._tail_row_pricer(messages)
        return sum(price(i) for i in range(len(messages)))

    def observe_real_prompt_tokens(self, real_tokens: Any, message_rough_tokens: Any) -> None:
        try:
            point = (int(real_tokens or 0), int(message_rough_tokens or 0))
        except (TypeError, ValueError):
            return
        fitted = fit_landing(point, self._post_compaction_point)
        if fitted is not None:
            self.real_token_ratio, self.real_overhead_tokens = fitted
            return
        ratio = bounded_ratio(point[0], self.request_overhead_tokens + point[1])
        if ratio is not None:
            self.real_token_ratio, self.real_overhead_tokens = ratio, int(ratio * self.request_overhead_tokens)

    def note_landing_messages(self, messages: list[dict[str, Any]]) -> None:
        if self.landing_target_tokens:
            self._landing_messages_rough = self._messages_rough(messages)

    def _real_overhead_tokens(self) -> int:
        return self.real_overhead_tokens or int(self.real_token_ratio * self.request_overhead_tokens)

    def _summary_reserve_tokens(self, messages: list[dict[str, Any]]) -> int:
        from agent.context_compressor import (
            _CHARS_PER_TOKEN, _LEAN_SESSION_LOG_BUDGET_TOKENS, _SUMMARY_END_MARKER, SUMMARY_PREFIX,
            _content_text_for_contains,
        )
        from agent.model_metadata import estimate_tokens_rough

        session_log = _LEAN_SESSION_LOG_BUDGET_TOKENS if getattr(self, "tail_mode", "lean") == "lean" else 0
        framing = estimate_tokens_rough(SUMMARY_PREFIX + "\n\n" + _SUMMARY_END_MARKER)
        prior = max((
            estimate_tokens_rough(_content_text_for_contains(m.get("content")))
            for m in messages if self._is_context_summary_message(m)), default=0)
        return framing + summary_reserve_tokens(
            self.summary_max_chars, self.max_summary_tokens + session_log, _CHARS_PER_TOKEN, prior,
        )

    def _landing_tokens(self, message_rough: int) -> int:
        return self._real_overhead_tokens() + int(self.real_token_ratio * message_rough)

    def _plan_landing(self, messages: list[dict[str, Any]]) -> LandingPlan:
        target = self.landing_target_tokens
        reserve = self._summary_reserve_tokens(messages)
        budget, shrinkable = planned_tail_budget(
            self.tail_token_budget, target, self.real_token_ratio, self._real_overhead_tokens(),
            self.request_overhead_tokens, reserve,
        )
        plan = None
        for _ in range(LANDING_PLAN_ROUNDS):
            pruned, pruned_count = self._prune_old_tool_results(
                messages, protect_tail_count=self.protect_last_n, protect_tail_tokens=budget,
            )
            pruned = self._drop_blank_echoes(pruned)
            start, end = self._compress_window(pruned, None if budget == self.tail_token_budget else budget)
            # Lean mode demotes stale tail tool results before summary generation so stubs exist even if it aborts.
            if start < end and getattr(self, "tail_mode", "lean") == "lean":
                pruned = self._demote_stale_tail_tools(pruned, end)
            projected = self._landing_tokens(self._messages_rough(pruned[:start] + pruned[end:]) + reserve) if target else 0
            plan = LandingPlan(pruned, pruned_count, start, end, budget, projected)
            if not shrinkable or projected <= target or start >= end or budget <= LANDING_TAIL_FLOOR_TOKENS:
                break
            budget = next_tail_budget(budget)
        if target:
            logger.info(
                "Compaction landing plan: target ~%s real tokens, projected ~%s (tail budget %s, %.2f real per "
                "rough token, fixed prompt ~%s real)", f"{target:,}", f"{plan.projected_tokens:,}",
                f"{plan.tail_budget:,}", self.real_token_ratio, f"{self._real_overhead_tokens():,}",
            )
        return plan

    def _fit_summary_cap(self, summary: str) -> str:
        from agent.context_compressor import _CAPPED_SUMMARY_DROPPED, _CAPPED_SUMMARY_PRIORITY, _CAPPED_SUMMARY_REQUIRED
        return fit_summary_to_cap(
            summary, self.summary_max_chars, _CAPPED_SUMMARY_REQUIRED, _CAPPED_SUMMARY_PRIORITY, _CAPPED_SUMMARY_DROPPED,
        )


def prime_landing_estimate(agent: Any, messages: list) -> None:
    from agent.model_metadata import _estimate_tools_tokens_rough, estimate_tokens_rough
    from agent.usage_anchor import _anchor_matches

    compressor = agent.context_compressor
    if not callable(getattr(compressor, "observe_real_prompt_tokens", None)):
        return
    system_prompt = "\n".join(filter(None, (
        getattr(agent, "_cached_system_prompt", None), getattr(agent, "ephemeral_system_prompt", None))))
    tools = getattr(agent, "tools", None)
    compressor.request_overhead_tokens = estimate_tokens_rough(system_prompt) + (
        _estimate_tools_tokens_rough(tools) if tools else 0)
    anchor = getattr(agent, "_usage_anchor", None)
    if isinstance(anchor, dict) and _anchor_matches(messages, anchor):
        compressor.observe_real_prompt_tokens(
            anchor.get("prompt_tokens"), compressor._messages_rough(messages[:int(anchor["base_count"])]))
