from __future__ import annotations

import logging
import re
from dataclasses import dataclass
from typing import Any, Optional, Sequence

from agent.compression_marker import elide

logger = logging.getLogger(__name__)

LANDING_TAIL_FLOOR_TOKENS = 2_000
LANDING_PLAN_ROUNDS = 4
LANDING_SHRINK_STEP = 0.6
TAIL_SOFT_OVERRUN = 1.5
REAL_TOKEN_RATIO_BOUNDS = (0.5, 4.0)
FIT_MIN_SPREAD = 0.25
USER_WORDS_SHARE = 0.35
ANCHOR_SHARE = 0.10
LLM_BODY_SHARE = 0.55
SECTION_MIN_CHARS = 200
SUMMARY_GROWTH_MARGIN = 1.25

_GATEWAY_PREAMBLE_RE = re.compile(
    r'\A(?:\[Triggering message id: [^\n]*\]\s*)?(?:\[Replying to(?: your previous message)?: ".*?"\]\s*)?',
    re.DOTALL,
)
_SECTION_START_RE = re.compile(r"(?m)^## ")


@dataclass
class LandingPlan:
    messages: list
    pruned_count: int
    compress_start: int
    compress_end: int
    tail_budget: int
    projected_tokens: int


def bounded_ratio(real: Any, rough: Any) -> Optional[float]:
    try:
        real_value, rough_value = float(real), float(rough)
    except (TypeError, ValueError):
        return None
    if real_value <= 0 or rough_value <= 0:
        return None
    low, high = REAL_TOKEN_RATIO_BOUNDS
    return min(high, max(low, real_value / rough_value))


def landing_target(threshold_tokens: int, target_tokens: Any, target_ratio: Any) -> int:
    try:
        explicit = int(target_tokens or 0)
    except (TypeError, ValueError):
        explicit = 0
    if explicit > 0:
        return min(explicit, threshold_tokens) if threshold_tokens > 0 else explicit
    try:
        ratio = float(target_ratio or 0)
    except (TypeError, ValueError):
        ratio = 0.0
    return int(threshold_tokens * ratio) if 0 < ratio < 1 and threshold_tokens > 0 else 0


def fit_landing(point: tuple[int, int], prior: Optional[tuple[int, int]]) -> Optional[tuple[float, int]]:
    if not prior:
        return None
    (real_a, rough_a), (real_b, rough_b) = point, prior
    if min(real_a, real_b, rough_a, rough_b) <= 0 or abs(rough_a - rough_b) < FIT_MIN_SPREAD * max(rough_a, rough_b):
        return None
    ratio = (real_a - real_b) / (rough_a - rough_b)
    low, high = REAL_TOKEN_RATIO_BOUNDS
    overhead = int(real_a - ratio * rough_a)
    if not low <= ratio <= high or not 0 <= overhead < min(real_a, real_b):
        return None
    return ratio, overhead


def planned_tail_budget(
    default_budget: int, target: int, ratio: float, overhead_real: int, overhead_rough: int, summary_reserve: int,
) -> tuple[int, bool]:
    if target <= 0:
        return default_budget, False
    if target <= overhead_rough + summary_reserve + LANDING_TAIL_FLOOR_TOKENS:
        logger.info(
            "Compaction landing target %d is out of reach (fixed prompt ~%d rough tokens); keeping the default "
            "tail budget", target, overhead_rough,
        )
        return default_budget, False
    room = int((target - overhead_real) / ratio) - summary_reserve
    return min(default_budget, max(LANDING_TAIL_FLOOR_TOKENS, int(room / TAIL_SOFT_OVERRUN))), True


def next_tail_budget(budget: int) -> int:
    return max(LANDING_TAIL_FLOOR_TOKENS, int(budget * LANDING_SHRINK_STEP))


def _text_of(content: Any) -> str:
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "\n".join(
            part if isinstance(part, str) else str(part.get("text") or "")
            for part in content if isinstance(part, (str, dict))
        )
    return ""


def _kanban_wake_markers() -> tuple[str, ...]:
    markers: list[str] = []
    try:
        from agent.i18n import DEFAULT_LANGUAGE, t
        for lang in (None, DEFAULT_LANGUAGE):
            template = t("gateway.kanban.wake.message", lang=lang)
            prefix = template.split("{", 1)[0]
            if len(prefix) >= 4 and prefix != "gateway.kanban.wake.message":
                markers.append(prefix)
    except Exception:
        logger.debug("kanban wake template unavailable", exc_info=True)
    return tuple(dict.fromkeys(markers))


def _kanban_wake_guidance() -> tuple[str, ...]:
    texts: list[str] = []
    try:
        from agent.i18n import DEFAULT_LANGUAGE, t
        for lang in (None, DEFAULT_LANGUAGE):
            text = t("gateway.kanban.wake.guidance", lang=lang)
            if text and text != "gateway.kanban.wake.guidance":
                texts.append(text)
    except Exception:
        logger.debug("kanban wake guidance unavailable", exc_info=True)
    return tuple(dict.fromkeys(texts))


def _internal_notification_footer() -> str:
    try:
        from gateway.run_notifications import INTERNAL_NOTIFICATION_FOOTER
    except ImportError:
        logger.debug("gateway notification footer unavailable", exc_info=True)
        return "[INTERNAL NOTIFICATION — generated by the Hermes gateway"
    return INTERNAL_NOTIFICATION_FOOTER


def is_machine_notice(text: str) -> bool:
    stripped = text.strip()
    if _internal_notification_footer() in stripped:
        return True
    if any(stripped.startswith(prefix) for prefix in _kanban_wake_markers()):
        return True
    return any(stripped.endswith(guidance) for guidance in _kanban_wake_guidance())


def typed_words_of_skill_turn(text: str) -> Optional[str]:
    """The words of a ``/skill``, bundle or auto-load turn as the user typed them (upstream's
    ``describe_skill_invocation``); other text unchanged; None when the scaffold is all there is."""
    from agent.skill_commands import _AUTO_LOAD_PREFIX, _SKILL_INVOCATION_PREFIX, describe_skill_invocation
    if not text.startswith((_SKILL_INVOCATION_PREFIX, _AUTO_LOAD_PREFIX)):
        return text
    words = describe_skill_invocation(text, separator=" ")
    return words.strip() if isinstance(words, str) and words.strip() else None


def human_user_words(message: Any, *, steer_kind: str = "steer") -> Optional[str]:
    if not isinstance(message, dict) or message.get("role") != "user":
        return None
    kind = message.get("display_kind")
    if kind and kind != steer_kind:
        return None
    text = _text_of(message.get("content")).strip()
    if not text or is_machine_notice(text):
        return None
    words = typed_words_of_skill_turn(text)
    if not words:
        return None
    words = _GATEWAY_PREAMBLE_RE.sub("", words, count=1).strip()
    return words or None


